"""``lovia web init-ui [DIR]`` — a starter UI directory for ``ChatUI(assets=...)``.

Writes ``index.html`` (every template block, commented out), ``theme.css``
(every design token with its default, commented out) and ``extension.js`` (a
type-checked ``window.lovia`` skeleton). The blocks and tokens are read from
the bundled page and stylesheet, so a scaffold always matches the installed
version.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from .. import __version__

_HERE = Path(__file__).parent
_PAGE = _HERE / "templates" / "index.html"
_STYLES = _HERE / "static" / "styles.css"
_TYPES = _HERE / "static" / "lovia.d.ts"

_BLOCK = re.compile(r"\{%\s*block\s+(\w+)\s*%\}")
_RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")
_COMMENT = re.compile(r"/\*.*?\*/", re.S)
_TOKEN = re.compile(r"(--[\w-]+)\s*:\s*([^;]+);")


def _blocks() -> list[str]:
    return list(dict.fromkeys(_BLOCK.findall(_PAGE.read_text(encoding="utf-8"))))


def _tokens() -> tuple[dict[str, str], dict[str, str]]:
    """The bundled tokens: (light / root values, dark values)."""
    css = _STYLES.read_text(encoding="utf-8")
    start = css.index("Design tokens")
    section = css[start : css.index("Reset & Base", start)]
    light: dict[str, str] = {}
    dark: dict[str, str] = {}
    for selector, body in _RULE.findall(_COMMENT.sub("", section)):
        target = dark if "dark" in selector else light
        for name, value in _TOKEN.findall(body):
            target[name] = " ".join(value.split())
    return light, dark


def _decls(tokens: dict[str, str]) -> str:
    return "\n".join(f"  /* {name}: {value}; */" for name, value in tokens.items())


def page() -> str:
    blocks = "\n".join(f"{{% block {b} %}}{{% endblock %}}" for b in _blocks())
    return f"""\
{{% extends "lovia/index.html" %}}
{{# Your page: the bundled one, plus the blocks you fill. Generated by
   `lovia web init-ui` (lovia {__version__}). Move a block out of this comment
   to fill it; `{{{{ super() }}}}` inside keeps a block's bundled content
   (welcome, sidebar_header have some). Style the page through theme.css and
   the data-part attributes; ids and class names are internal.

{blocks}
#}}
"""


def theme() -> str:
    light, dark = _tokens()
    shared = {k: v for k, v in light.items() if k not in dark}
    themed = {k: v for k, v in light.items() if k in dark}
    return f"""\
/* Your theme, on top of lovia's design tokens. Generated by `lovia web
   init-ui` (lovia {__version__}): every token with its default, commented out —
   uncomment the ones you change. The bundled stylesheet sits in the `lovia`
   cascade layer, so any rule here wins over it. --lv-accent-hover, -soft and
   -text derive from --lv-accent. */

/* Both themes. */
:root {{
{_decls(shared)}
}}

/* Colors, per theme (one set on :root instead would apply to both). */
[data-theme="light"] {{
{_decls(themed)}
}}

[data-theme="dark"] {{
{_decls(dark)}
}}
"""


def extension() -> str:
    return f"""\
// @ts-check
/// <reference path="{_TYPES.resolve().as_posix()}" />
// Your extension, imported before the page starts. Generated by `lovia web
// init-ui` (lovia {__version__}); the reference above — this install's
// lovia.d.ts — types `window.lovia` for your editor.

const {{ lovia }} = window;

// A plain-language line for one of your tools' cards:
// lovia.registerToolView('order_status', {{
//   summary: (tool) => (tool.status === 'done' ? 'Looked up the order' : 'Looking up the order…'),
// }});

// React to the chat:
// lovia.on('run-end', ({{ status }}) => {{
//   if (status === 'error') lovia.toast('Something went wrong', {{ type: 'error' }});
// }});

// A page of your own beside the chat, opened by a link such as
// <a href="?view=dashboard">Dashboard</a> in the sidebar_nav block:
// lovia.registerView('dashboard', {{
//   title: 'Dashboard',
//   render(el, ctx) {{
//     el.textContent = `Dashboard ${{ctx.path}}`; // ctx.path: ?view=dashboard/<path>
//   }},
// }});
"""


FILES = {"index.html": page, "theme.css": theme, "extension.js": extension}


def init_ui(directory: Path) -> list[Path]:
    """Write the starter files into ``directory``; refuse to overwrite any."""
    targets = [directory / name for name in FILES]
    existing = [p for p in targets if p.exists()]
    if existing:
        names = ", ".join(str(p) for p in existing)
        raise FileExistsError(f"refusing to overwrite {names}")
    directory.mkdir(parents=True, exist_ok=True)
    for path in targets:
        path.write_text(FILES[path.name](), encoding="utf-8")
    return targets


def main(argv: list[str], *, prog: str) -> int:
    parser = argparse.ArgumentParser(
        prog=prog,
        description="Write a starter UI directory (page blocks, theme tokens, "
        "an extension script) for ChatUI(assets=...).",
    )
    parser.add_argument(
        "directory", nargs="?", default="ui", help="where to write (default: ui)"
    )
    args = parser.parse_args(argv)
    directory = Path(args.directory)
    try:
        written = init_ui(directory)
    except FileExistsError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    for path in written:
        print(f"wrote {path}")
    print(
        "\nServe it with your agent:\n\n"
        "    from lovia.web import ChatUI, create_app\n"
        f'    ui = ChatUI(assets="{directory.as_posix()}", '
        'scripts=["extension.js"], styles=["theme.css"])\n'
        "    app = create_app(agent, ui=ui)\n"
    )
    return 0
